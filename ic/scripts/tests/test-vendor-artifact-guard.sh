#!/usr/bin/env bash
# Tests for scripts/vendor-artifact-guard.sh and its build wiring (mt-admin
# build_tenant, build-wasm-extensions.sh). cargo never re-checks vendored
# crates, so a crate patched in place at an unchanged version must be cleaned
# from reused target dirs; otherwise upgrades link against the pre-patch
# artifacts (the WI#292 rig-core E0599 that CI, building from scratch, missed).
set -euo pipefail

TEST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPTS_DIR="$TEST_DIR/.."
GUARD="$SCRIPTS_DIR/vendor-artifact-guard.sh"
ADMIN_SCRIPT="$SCRIPTS_DIR/lunarwing-mt-admin.sh"
WASM_SCRIPT="$SCRIPTS_DIR/build-wasm-extensions.sh"
STATE_HEADER="# lunarwing vendor-artifact-guard state v1"

fixture="$(mktemp -d)"
trap 'rm -rf "$fixture"' EXIT
failures=0

pass() { printf 'PASS: %s\n' "$1"; }
fail() { printf 'FAIL: %s\n' "$1"; failures=$((failures + 1)); }
check() {  # <label> <command...>
  local label="$1"
  shift
  if "$@"; then pass "$label"; else fail "$label"; fi
}

# ── Fixture checkout: ic/scripts/<guard>, ic/vendor/<crates>, ic/Cargo.lock ──
ic="$fixture/ic"
mkdir -p "$ic/scripts" "$ic/vendor" "$fixture/bin"
cp "$GUARD" "$ic/scripts/vendor-artifact-guard.sh"

vendor_crate() {  # <dir> <name> <version> <checksum-file-body>
  mkdir -p "$ic/vendor/$1"
  printf '[package]\nedition = "2021"\nname = "%s"\nversion = "%s"\n\n[lib]\nname = "%s"\n' \
    "$2" "$3" "${2//-/_}" >"$ic/vendor/$1/Cargo.toml"
  printf '%s\n' "$4" >"$ic/vendor/$1/.cargo-checksum.json"
}
# rig-core's checksum file is pretty-printed, like the real patched one.
rig_checksums() {  # <lib.rs digest>
  printf '{\n "files": {\n  "src/lib.rs": "%s"\n },\n "package": "d8731dd5"\n}' "$1"
}
vendor_crate rig-core rig-core 0.40.0 "$(rig_checksums 1111)"
: >"$ic/vendor/rig-core/LUNARWING-PATCH.md"
vendor_crate serde serde 1.0.0 '{"files":{"src/lib.rs":"2222"},"package":"5e4de"}'
vendor_crate leftpad leftpad 0.1.0 '{"files":{"src/lib.rs":"3333"},"package":"1ef7"}'

write_lock() {  # <name@version>... (registry packages of the fixture workspace)
  local spec
  {
    printf '# This file is automatically @generated by Cargo.\nversion = 4\n\n'
    printf '[[package]]\nname = "app"\nversion = "0.1.0"\n'
    for spec in "$@"; do
      printf '\n[[package]]\nname = "%s"\nversion = "%s"\n' "${spec%@*}" "${spec#*@}"
      printf 'source = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "00"\n'
    done
  } >"$ic/Cargo.lock"
}
write_lock rig-core@0.40.0 serde@1.0.0

# Stub cargo: logs every call; `metadata` reports METADATA_TARGET_DIR, `clean`
# fails on demand, `build` creates the profile output dir like cargo would.
cat >"$fixture/bin/cargo" <<'SH'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$CARGO_CALLS"
case "${1:-}" in
  metadata)
    printf '{"packages":[],"target_directory":"%s","version":1}\n' "${METADATA_TARGET_DIR:?}"
    ;;
  clean)
    [[ "${FAIL_CLEAN:-false}" != true ]] || exit 101
    ;;
  build)
    profile=debug
    [[ " $* " != *" --profile release "* && " $* " != *" --release "* ]] || profile=release
    mkdir -p "${CARGO_TARGET_DIR:-$PWD/target}/$profile"
    ;;
esac
SH
chmod +x "$fixture/bin/cargo"
export CARGO_CALLS="$fixture/calls"
export METADATA_TARGET_DIR="$ic/target"

out=""
rc=0
run_guard() {  # [guard args...]; output in $out, exit status in $rc
  : >"$CARGO_CALLS"
  set +e
  out="$(cd "$ic" && env -u CARGO_BUILD_TARGET PATH="$fixture/bin:$PATH" \
    CARGO_TARGET_DIR="${GUARD_TARGET_DIR-$ic/target}" \
    bash scripts/vendor-artifact-guard.sh "$@" 2>&1)"
  rc=$?
  set -e
}
# Clean calls with the (separately asserted) --target-dir argument elided.
cleans() { sed -n 's/^clean --target-dir [^ ]* /clean /p' "$CARGO_CALLS"; }
state="$ic/target/release/.lunarwing-vendor-state"
first_line() { head -n 1 "$1" 2>/dev/null || true; }

# ── Guard behavior ───────────────────────────────────────────────────────────

run_guard
check 'never-built target dir: nothing cleaned, nothing recorded' \
  test "$rc" -eq 0 -a -z "$(cleans)" -a ! -e "$state"

mkdir -p "$ic/target/release"
run_guard
check 'first guarded run on an existing target dir cleans the LUNARWING-PATCH.md crate' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile release -p rig-core'
check 'first run explains the one-time clean' \
  grep -qF 'cleaning locally patched vendored crates once: rig-core@0.40.0' <<<"$out"
check 'cargo clean targets the tracked target dir explicitly' \
  grep -qxF "clean --target-dir $ic/target --profile release -p rig-core" "$CARGO_CALLS"
check 'vendor state is recorded in the profile dir' \
  test "$(first_line "$state")" = "$STATE_HEADER"

run_guard
check 'unchanged vendor tree cleans nothing' test "$rc" -eq 0 -a -z "$(cleans)"

vendor_crate rig-core rig-core 0.40.0 "$(rig_checksums 1112)"
run_guard
check 'crate patched in place at the same version is cleaned' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile release -p rig-core'
check 'in-place change is reported with its name@version' \
  grep -qF 'changed in place since the last build' <<<"$out"
run_guard
check 'recorded state prevents a repeat clean' test "$rc" -eq 0 -a -z "$(cleans)"

vendor_crate serde serde 1.0.0 '{"files":{"src/lib.rs":"2223"},"package":"5e4de"}'
run_guard
check 'any crate patched in place is cleaned, with or without a marker' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile release -p serde'

vendor_crate serde serde 1.0.1 '{"files":{"src/lib.rs":"2224"},"package":"5e4df"}'
write_lock rig-core@0.40.0 serde@1.0.1
run_guard
check 'version bumps are left to cargo' test "$rc" -eq 0 -a -z "$(cleans)"

vendor_crate leftpad leftpad 0.1.0 '{"files":{"src/lib.rs":"3334"},"package":"1ef7"}'
run_guard
check 'crate outside this workspace is not cleaned' test "$rc" -eq 0 -a -z "$(cleans)"
write_lock rig-core@0.40.0 serde@1.0.1 leftpad@0.1.0
run_guard
check 'that change stays pending until the workspace builds the crate' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile release -p leftpad'

vendor_crate rig-core rig-core 0.40.0 "$(rig_checksums 1113)"
before="$(cat "$state")"
run_guard --dry-run
check 'dry run reports the clean without running it' \
  test "$rc" -eq 0 -a -z "$(cleans)"
check 'dry run prints the cargo command' \
  grep -qF 'would run in' <<<"$out"
check 'dry run leaves the recorded state alone' test "$(cat "$state")" = "$before"

export FAIL_CLEAN=true
run_guard
unset FAIL_CLEAN
check 'failed cargo clean fails the guard' test "$rc" -ne 0
check 'failure refuses to build against stale artifacts' \
  grep -qF 'refusing to build against stale artifacts of rig-core@0.40.0' <<<"$out"
check 'failed clean does not advance the recorded state' test "$(cat "$state")" = "$before"
run_guard
check 'failed clean is retried on the next build' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile release -p rig-core'

printf 'garbage\n' >"$state"
run_guard
check 'unrecognized state file is treated as a first run' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile release -p rig-core'

rm -rf "$ic/target"
mkdir -p "$ic/target/release"
run_guard --record
check '--record stores the baseline after a fresh build' \
  test "$rc" -eq 0 -a "$(first_line "$state")" = "$STATE_HEADER" -a -z "$(cleans)"
run_guard
check 'a recorded fresh build needs no first-run clean' test "$rc" -eq 0 -a -z "$(cleans)"

mkdir -p "$ic/target/wasm32-wasip2/release"
run_guard --target wasm32-wasip2
check '--target cleans the cross-compiled profile dir' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile release --target wasm32-wasip2 -p rig-core'
check '--target records state under the triple' \
  test -f "$ic/target/wasm32-wasip2/release/.lunarwing-vendor-state"

mkdir -p "$ic/target/debug"
run_guard --profile dev
check 'dev profile maps to target/debug' \
  test "$rc" -eq 0 -a "$(cleans)" = 'clean --profile dev -p rig-core' \
  -a -f "$ic/target/debug/.lunarwing-vendor-state"

mkdir -p "$fixture/meta-target/release"
GUARD_TARGET_DIR="" METADATA_TARGET_DIR="$fixture/meta-target" run_guard
check 'target dir comes from cargo metadata without CARGO_TARGET_DIR' \
  test "$rc" -eq 0 -a -f "$fixture/meta-target/release/.lunarwing-vendor-state"
check 'cargo clean targets the metadata-reported target dir' \
  grep -qxF "clean --target-dir $fixture/meta-target --profile release -p rig-core" "$CARGO_CALLS"

run_guard --bogus
check 'unknown arguments are rejected' test "$rc" -ne 0
run_guard --profile '../x'
check 'path-like profile names are rejected' test "$rc" -ne 0

# ── mt-admin build_tenant wiring ─────────────────────────────────────────────
(
  # shellcheck disable=SC1090
  source "$ADMIN_SCRIPT"
  # shellcheck disable=SC2034  # consumed by the sourced mt-admin library
  BUILD_LOCK="$fixture/build.lock" PROFILE=release BUILD_JOBS=2
  tenant_repo() { printf '%s\n' "$ic"; }
  tenant_env_dir() { printf '%s/env\n' "$fixture"; }
  flock() { return 0; }
  say() { :; }
  sudo() { return 0; }
  _run_tenant_build() { printf '%s\n' "$2" >>"$fixture/tenant-cmds"; }
  build_tenant fixture >/dev/null 2>&1
) || true
guard_path="$ic/scripts/vendor-artifact-guard.sh"
lunarwing_cmd="$(sed -n 1p "$fixture/tenant-cmds" 2>/dev/null || true)"
bridge_cmd="$(sed -n 2p "$fixture/tenant-cmds" 2>/dev/null || true)"
check 'tenant lunarwing build runs the guard first' \
  grep -qF "bash '$guard_path' --manifest-dir '$ic' --profile 'release' && cargo build --profile 'release' -j2 --bin lunarwing" <<<"$lunarwing_cmd"
check 'tenant lunarwing build records the vendor state after success' \
  grep -qF -- "--bin lunarwing && { bash '$guard_path' --manifest-dir '$ic' --profile 'release' --record || true; }" <<<"$lunarwing_cmd"
check 'tenant xmpp-bridge build is guarded in its own cargo root' \
  grep -qF "bash '$guard_path' --manifest-dir '$ic/bridges/xmpp-bridge' --profile 'release' && cargo build --profile 'release' -j2" <<<"$bridge_cmd"

# Execute the generated command against the fixture: clean, build, record.
cmd="$(bash -c 'source "$1"; PROFILE=release; BUILD_JOBS=2; _vendor_guarded_cargo_build "$2" "$2" --bin lunarwing' _ "$ADMIN_SCRIPT" "$ic")"
vendor_crate rig-core rig-core 0.40.0 "$(rig_checksums 1114)"
: >"$CARGO_CALLS"
set +e
(cd / && env -u CARGO_TARGET_DIR PATH="$fixture/bin:$PATH" bash -c "$cmd" >/dev/null 2>&1)
rc=$?
set -e
calls="$(grep -E '^(clean|build)' "$CARGO_CALLS" | tr '\n' '|')"
check 'generated tenant command cleans stale crates, then builds' \
  test "$rc" -eq 0 -a "$calls" = "clean --target-dir $ic/target --profile release -p rig-core|build --profile release -j2 --bin lunarwing|"
mv "$guard_path" "$guard_path.off"
: >"$CARGO_CALLS"
set +e
(cd / && env -u CARGO_TARGET_DIR PATH="$fixture/bin:$PATH" bash -c "$cmd" >/dev/null 2>&1)
rc=$?
set -e
calls="$(grep -vE '^metadata' "$CARGO_CALLS" | tr '\n' '|')"
check 'checkouts without the guard still build' \
  test "$rc" -eq 0 -a "$calls" = 'build --profile release -j2 --bin lunarwing|'
mv "$guard_path.off" "$guard_path"

# ── build-wasm-extensions.sh wiring ──────────────────────────────────────────
wasm="$fixture/wasm/ic"
mkdir -p "$wasm/scripts" "$wasm/registry/tools" "$wasm/registry/channels" "$wasm/tools-src/demo" "$fixture/wasm-bin"
cp "$WASM_SCRIPT" "$wasm/scripts/build-wasm-extensions.sh"
printf '{"source":{"dir":"tools-src/demo","crate_name":"demo-tool"}}\n' >"$wasm/registry/tools/demo-tool.json"
printf '[package]\nname = "demo-tool"\nversion = "0.1.0"\n' >"$wasm/tools-src/demo/Cargo.toml"
: >"$wasm/tools-src/demo/Cargo.lock"
cat >"$wasm/scripts/vendor-artifact-guard.sh" <<'SH'
#!/usr/bin/env bash
printf 'guard %s\n' "$*" >>"$WASM_CALLS"
exit "${GUARD_RC:-0}"
SH
cat >"$fixture/wasm-bin/rustup" <<'SH'
#!/usr/bin/env bash
[[ "$*" != "target list --installed" ]] || printf 'wasm32-wasip2 (installed)\n'
SH
cat >"$fixture/wasm-bin/cargo" <<'SH'
#!/usr/bin/env bash
printf 'cargo %s\n' "$*" >>"$WASM_CALLS"
mkdir -p tools-src/demo/target/wasm32-wasip2/release
printf 'component\n' >tools-src/demo/target/wasm32-wasip2/release/demo_tool.wasm
SH
chmod +x "$fixture/wasm-bin/rustup" "$fixture/wasm-bin/cargo"
export WASM_CALLS="$fixture/wasm-calls"

: >"$WASM_CALLS"
set +e
PATH="$fixture/wasm-bin:$PATH" bash "$wasm/scripts/build-wasm-extensions.sh" --tools >/dev/null 2>&1
rc=$?
set -e
guard_args='--manifest-dir tools-src/demo --target-dir tools-src/demo/target --profile release --target wasm32-wasip2'
expected="guard $guard_args|cargo build --locked --release --target wasm32-wasip2 --manifest-path tools-src/demo/Cargo.toml|guard $guard_args --record|"
check 'WASM extension build is guarded before and recorded after' \
  test "$rc" -eq 0 -a "$(tr '\n' '|' <"$WASM_CALLS")" = "$expected"

: >"$WASM_CALLS"
set +e
wasm_out="$(GUARD_RC=1 PATH="$fixture/wasm-bin:$PATH" bash "$wasm/scripts/build-wasm-extensions.sh" --tools 2>&1)"
rc=$?
set -e
check 'WASM extension fails without building when the guard fails' \
  test "$rc" -ne 0 -a "$(grep -c '^cargo' "$WASM_CALLS" || true)" -eq 0
check 'WASM guard failure is reported' \
  grep -qF 'FAIL demo-tool (could not clean stale vendored-crate artifacts)' <<<"$wasm_out"

if [[ "$failures" -ne 0 ]]; then
  printf 'RESULT: %d failure(s)\n' "$failures"
  exit 1
fi
printf 'RESULT: all vendor artifact guard tests passed\n'
