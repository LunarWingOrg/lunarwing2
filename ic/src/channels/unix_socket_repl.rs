    #[test]
    fn status_payload_maps_core_variants() {
        let (kind, _content, _data) =
            repl_status_payload(&StatusUpdate::StreamChunk("chunk".into()))
                .expect("stream chunk maps");
        assert_eq!(kind, ReplStatusKind::StreamChunk);

        let (kind, _, data) = repl_status_payload(&StatusUpdate::ToolCompleted {
            name: "web_search".into(),
            success: false,
            error: Some("boom".into()),
            parameters: Some("{}".into()),
        })
        .expect("tool completed maps");
        assert_eq!(kind, ReplStatusKind::ToolCompleted);
        assert_eq!(data["success"], false);

        assert!(
            repl_status_payload(&StatusUpdate::TurnCost {
                input_tokens: 1,
                output_tokens: 1,
                cost_usd: "0.00".into(),
            })
            .is_none()
        );
    }

