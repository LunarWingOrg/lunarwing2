//! Host-side git credential broker (WI#860).
//!
//! The container's git runs a generated `credential.helper` that speaks the
//! [git-credential protocol] to a Unix socket bind-mounted read-only into the
//! run. The socket is served by the daemon, which resolves the secret name
//! from host policy and answers with `username`/`password` lines. The secret
//! value never enters the container's environment, files, arguments, process
//! listings or command output: it only travels over the socket to the
//! requesting helper process.
//!
//! [git-credential protocol]: https://git-scm.com/docs/git-credential
//!
//! Trust boundary: the container can ask for any host it names, so the broker
//! answers only for the exact hosts bound by `SANDBOX_GIT_CREDENTIALS` for
//! this call. It never echoes the secret in a log line or an error.

use std::collections::HashMap;
use std::path::Path;

use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader};
use tokio::net::{UnixListener, UnixStream};

use crate::sandbox::error::{Result, SandboxError};
use crate::sandbox::git_grant::{GitCredentialBinding, GIT_CREDENTIAL_SOCKET};
use crate::sandbox::proxy::CredentialResolver;

/// A resolved credential for one host. `Debug` is redacted.
pub struct HostCredential {
    pub username: String,
    password: secrecy::SecretString,
}

impl std::fmt::Debug for HostCredential {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("HostCredential")
            .field("username", &self.username)
            .field("password", &"<redacted>")
            .finish()
    }
}

impl HostCredential {
    pub fn new(username: impl Into<String>, password: secrecy::SecretString) -> Self {
        Self {
            username: username.into(),
            password,
        }
    }
}

/// The host-side broker for one execution.
pub struct GitCredentialBroker {
    directory: tempfile::TempDir,
    bindings: HashMap<String, String>,
    username: String,
}

impl GitCredentialBroker {
    /// Create a private directory under the shared relay parent, so the
    /// container CLI's mount namespace can still resolve it (the same policy
    /// as the proxy relay).
    pub fn create(bindings: &[GitCredentialBinding]) -> Result<Self> {
        let base = crate::sandbox::proxy::relay::relay_parent_dir().map_err(|error| {
            SandboxError::ProxyError {
                reason: format!("cannot locate a shared directory for the git credential broker: {error}"),
            }
        })?;
        let directory = tempfile::Builder::new()
            .prefix("lw-git-cred-")
            .tempdir_in(&base)
            .map_err(|error| SandboxError::ProxyError {
                reason: format!(
                    "cannot create the git credential broker directory in {}: {error}",
                    base.display()
                ),
            })?;
        let username = bindings
            .first()
            .map(|binding| binding.username.clone())
            .unwrap_or_else(|| "lunarwing".to_string());
        Ok(Self {
            directory,
            bindings: bindings
                .iter()
                .map(|binding| (binding.host.clone(), binding.secret_name.clone()))
                .collect(),
            username,
        })
    }

    /// Host directory bind-mounted at
    /// [`crate::sandbox::git_grant::GIT_CREDENTIAL_MOUNT`].
    pub fn path(&self) -> &Path {
        self.directory.path()
    }

    /// The helper script written into the broker directory. It carries the
    /// socket path and the git-credential protocol only, never a secret.
    pub fn helper_script(&self) -> String {
        let socket = format!(
            "{}/{}",
            crate::sandbox::git_grant::GIT_CREDENTIAL_MOUNT,
            GIT_CREDENTIAL_SOCKET
        );
        format!(
            "#!/bin/sh\n\
             # Generated by LunarWing (WI#860). Asks the host broker; holds no secret.\n\
             exec python3 - \"$1\" \"{socket}\" <<'PY'\n\
             import socket, sys\n\
             action, path = sys.argv[1], sys.argv[2]\n\
             payload = sys.stdin.read()\n\
             if action != 'get':\n\
                 sys.exit(0)\n\
             client = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)\n\
             client.settimeout(10)\n\
             client.connect(path)\n\
             client.sendall(payload.encode() + b'\\n')\n\
             client.shutdown(socket.SHUT_WR)\n\
             chunks = []\n\
             while True:\n\
                 chunk = client.recv(4096)\n\
                 if not chunk:\n\
                     break\n\
                 chunks.append(chunk)\n\
             sys.stdout.write(b''.join(chunks).decode())\n\
             PY\n"
        )
    }

    /// Write the helper script into the broker directory. The socket itself
    /// is created by [`Self::serve`] after the directory is mounted.
    pub fn write_helper(&self) -> Result<()> {
        let helper = self.directory.path().join("helper.sh");
        std::fs::write(&helper, self.helper_script()).map_err(|error| {
            SandboxError::ProxyError {
                reason: format!("cannot write the git credential helper: {error}"),
            }
        })?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&helper, std::fs::Permissions::from_mode(0o755)).map_err(
                |error| SandboxError::ProxyError {
                    reason: format!("cannot mark the git credential helper executable: {error}"),
                },
            )?;
        }
        Ok(())
    }

    /// Serve the broker until the returned future is dropped or `shutdown`
    /// fires. Each connection answers one `git-credential get` request.
    pub async fn serve(
        &self,
        resolver: std::sync::Arc<dyn CredentialResolver>,
    ) -> Result<(tokio::task::JoinHandle<()>, tokio::sync::oneshot::Sender<()>)> {
        let socket = self.directory.path().join(GIT_CREDENTIAL_SOCKET);
        let listener = UnixListener::bind(&socket).map_err(|error| SandboxError::ProxyError {
            reason: format!("cannot bind the git credential broker socket: {error}"),
        })?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            // The container user (1000) is not the daemon user; the socket
            // must be reachable by it while the directory stays private.
            std::fs::set_permissions(&socket, std::fs::Permissions::from_mode(0o666)).map_err(
                |error| SandboxError::ProxyError {
                    reason: format!("cannot set the git credential socket mode: {error}"),
                },
            )?;
        }
        let bindings = self.bindings.clone();
        let username = self.username.clone();
        let (shutdown_tx, mut shutdown_rx) = tokio::sync::oneshot::channel::<()>();
        let handle = tokio::spawn(async move {
            loop {
                tokio::select! {
                    _ = &mut shutdown_rx => break,
                    accepted = listener.accept() => {
                        let Ok((stream, _)) = accepted else { break };
                        let bindings = bindings.clone();
                        let username = username.clone();
                        let resolver = resolver.clone();
                        tokio::spawn(async move {
                            if let Err(error) = answer(stream, &bindings, &username, resolver).await {
                                // Never echo a secret or the request body.
                                tracing::debug!(error = %error, "git credential broker request failed");
                            }
                        });
                    }
                }
            }
        });
        Ok((handle, shutdown_tx))
    }
}

/// Answer one `git-credential get` request. A request for an unbound host
/// gets an empty answer, which git treats as "no credential".
async fn answer(
    stream: UnixStream,
    bindings: &HashMap<String, String>,
    username: &str,
    resolver: std::sync::Arc<dyn CredentialResolver>,
) -> std::io::Result<()> {
    let (read_half, mut write_half) = stream.into_split();
    let mut reader = BufReader::new(read_half);
    let mut host: Option<String> = None;
    let mut line = String::new();
    loop {
        line.clear();
        if reader.read_line(&mut line).await? == 0 {
            break;
        }
        let trimmed = line.trim_end_matches(['\r', '\n']);
        if trimmed.is_empty() {
            break;
        }
        if let Some(value) = trimmed.strip_prefix("host=") {
            host = Some(value.trim().to_ascii_lowercase());
        }
    }
    let Some(host) = host else {
        return Ok(());
    };
    let Some(secret_name) = bindings.get(&host) else {
        return Ok(());
    };
    let Some(secret) = resolver.resolve(secret_name).await else {
        return Ok(());
    };
    let response = format!("username={username}\npassword={secret}\n\n");
    write_half.write_all(response.as_bytes()).await?;
    write_half.flush().await
}

#[cfg(test)]
mod tests {
    use super::*;
    use secrecy::SecretString;

    struct FixedResolver;

    #[async_trait::async_trait]
    impl CredentialResolver for FixedResolver {
        async fn resolve(&self, name: &str) -> Option<String> {
            (name == "git_read_token").then(|| "s3cret-value".to_string())
        }
    }

    fn bindings() -> Vec<GitCredentialBinding> {
        GitCredentialBinding::parse_spec("git.example.test=git_read_token").unwrap()
    }

    #[tokio::test]
    async fn broker_answers_only_for_a_bound_host_and_never_logs_the_secret() {
        let broker = GitCredentialBroker::create(&bindings()).unwrap();
        let (handle, shutdown) = broker.serve(std::sync::Arc::new(FixedResolver)).await.unwrap();
        let socket = broker.path().join(GIT_CREDENTIAL_SOCKET);

        let answer = ask(&socket, "host=git.example.test\nprotocol=https\n\n").await;
        assert_eq!(answer, "username=lunarwing\npassword=s3cret-value\n\n");

        let other = ask(&socket, "host=evil.example.test\nprotocol=https\n\n").await;
        assert_eq!(other, "");

        let _ = shutdown.send(());
        let _ = handle.await;
        assert!(!broker.helper_script().contains("s3cret-value"));
        assert!(broker.helper_script().contains(GIT_CREDENTIAL_SOCKET));
    }

    #[tokio::test]
    async fn broker_returns_nothing_when_the_secret_is_unset() {
        let broker = GitCredentialBroker::create(&bindings()).unwrap();
        let (handle, shutdown) = broker.serve(std::sync::Arc::new(NoCredentialResolver)).await.unwrap();
        let socket = broker.path().join(GIT_CREDENTIAL_SOCKET);
        assert_eq!(ask(&socket, "host=git.example.test\n\n").await, "");
        let _ = shutdown.send(());
        let _ = handle.await;
    }

    #[tokio::test]
    async fn helper_script_carries_no_secret_and_names_the_broker_socket() {
        let broker = GitCredentialBroker::create(&bindings()).unwrap();
        let script = broker.helper_script();
        assert!(script.contains("/run/lunarwing-git-credential/broker.sock"));
        assert!(!script.contains("s3cret"));
        assert!(!script.contains("git_read_token"));
        let _ = SecretString::from("unused");
    }

    async fn ask(socket: &Path, request: &str) -> String {
        use tokio::io::AsyncReadExt;
        let mut stream = UnixStream::connect(socket).await.unwrap();
        stream.write_all(request.as_bytes()).await.unwrap();
        stream.shutdown().await.unwrap();
        let mut answer = String::new();
        tokio::time::timeout(
            std::time::Duration::from_secs(5),
            stream.read_to_string(&mut answer),
        )
        .await
        .unwrap()
        .unwrap();
        answer
    }
}
